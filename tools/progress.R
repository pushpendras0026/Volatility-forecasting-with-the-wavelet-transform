script<-sub('^--file=','',grep('^--file=',commandArgs(),value=TRUE)[1]);root<-dirname(dirname(normalizePath(script,winslash='/')))
pointer<-file.path(root,'results',if(file.exists(file.path(root,'results/RUNNING.txt')))'RUNNING.txt'else'LATEST.txt')
run<-file.path(root,'results',basename(trimws(readLines(pointer)[1])))
done<-list.files(run,'^COMPLETE.rds$',recursive=TRUE,full.names=TRUE)
status<-lapply(done,function(f)tryCatch(readRDS(f),error=function(e)NULL))
if(length(status))print(with(do.call(rbind,lapply(status,function(z)z[,c('phase','scenario','status')])),table(phase,scenario,status)))
files<-list.files(file.path(run,'historical/baseline'),'^progress.csv$',recursive=TRUE,full.names=TRUE)
later<-list.files(file.path(run,'later/baseline'),'^progress.csv$',recursive=TRUE,full.names=TRUE)
rows<-lapply(c(files,later),function(f)tryCatch(read.csv(f),error=function(e)NULL))
if(length(rows))print(do.call(rbind,rows),row.names=FALSE)
errors<-list.files(run,'^ERROR.txt$',recursive=TRUE,full.names=TRUE)
if(length(errors))for(f in errors)cat(f,': ',readLines(f),'\n')
